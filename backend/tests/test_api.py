def test_model_error_maps_to_503(client, monkeypatch):
    """When the inference layer reports the model unavailable, the API
    must fail honestly with 503 — never fabricate a result."""
    from app.services import birdnet_service

    def boom(_path):
        raise birdnet_service.ModelError(
            "BirdNET-Analyzer is not installed in the backend environment."
        )

    monkeypatch.setattr(birdnet_service, "run_inference", boom)
    r = client.post(
        "/api/analyze",
        files={"file": ("tone.wav", _wav_bytes(), "audio/wav")},
    )
    assert r.status_code == 503
    assert "not installed" in r.json()["detail"]


