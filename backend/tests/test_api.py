"""API contract + input-validation tests (fast, no TF/model needed)."""
from __future__ import annotations

import io

import soundfile as sf
import numpy as np

MODEL_INFO_KEYS = {
    "model_name", "model_version", "model_source", "model_license",
    "code_license", "attribution", "input_sample_rate", "clip_seconds",
    "label_count", "offline_after_download",
}
ANALYZE_KEYS = {
    "status", "predictions", "audio", "model", "note",
    "is_demo_fixture", "source_label",
}


def _wav_bytes(seconds: float = 1.0, sr: int = 48000, amplitude: float = 0.2) -> bytes:
    t = np.linspace(0, seconds, int(sr * seconds), endpoint=False)
    sig = (amplitude * np.sin(2 * np.pi * 440 * t)).astype("float32")
    buf = io.BytesIO()
    sf.write(buf, sig, sr, format="WAV", subtype="FLOAT")
    return buf.getvalue()


